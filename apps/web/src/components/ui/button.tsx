type ButtonProps = ButtonPrimitive.Props & VariantProps<typeof buttonVariants>;

export function rendersLink(render: ButtonProps['render']): render is ReactElement {
  if (!isValidElement<{ href?: unknown; to?: unknown }>(render)) return false;
  return render.props.href !== undefined || render.props.to !== undefined;
}

function LinkButton({
  className,
  variant = 'default',
  size = 'default',
  render,
  ...props
}: Omit<ButtonProps, 'render'> & { render: ReactElement }) {
  const { nativeButton: _ignored, ...anchorProps } = props;
  return useRender({
    defaultTagName: 'a',
    props: mergeProps<'a'>(
      {
        'data-slot': 'button',
        'data-variant': variant,
        'data-size': size,
        className: cn(buttonVariants({ variant, size, className })),
      } as ComponentProps<'a'>,
      anchorProps as ComponentProps<'a'>,
    ),
    render,
  });
}

function Button({
  className,
  variant = 'default',
  size = 'default',
  type = 'button',
  ...props
}: ButtonProps) {
  const { render } = props;
  if (rendersLink(render)) {
    return (
      <LinkButton className={className} variant={variant} size={size} {...props} render={render} />
    );
  }
  return (
    <ButtonPrimitive
      type={type}
      data-slot="button"
      data-variant={variant}
      data-size={size}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  );
}

export { Button, buttonVariants };
