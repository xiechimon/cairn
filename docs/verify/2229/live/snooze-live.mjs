import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
const W = '/Users/xmon/Code/AgentProjects/cairn/.claude/worktrees/bui-snooze-fix';
const require = createRequire(`${W}/apps/web/package.json`);
const { chromium } = require('@playwright/test');
const API = 'http://127.0.0.1:8791';
const WEB = 'http://127.0.0.1:5273';
const OUT = `${W}/docs/verify/2229/live`;
mkdirSync(OUT, { recursive: true });
const j = async (method, path, body) => {
  const res = await fetch(`${API}${path}`, { method, headers: { 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
  const text = await res.text();
  if (!res.ok) throw new Error(`${method} ${path} ${res.status} ${text}`);
  return text ? JSON.parse(text) : null;
};
const save = (name, data) => writeFileSync(`${OUT}/${name}.json`, `${JSON.stringify(data, null, 2)}\n`);
const teams = await j('GET', '/api/teams');
const teamId = teams[0].id;
const project = await j('POST', '/api/projects', { name: 'snooze-live' });
const a = await j('POST', `/api/projects/${project.id}/todos`, { title: 'Timed snooze thread', spec: 'live walk' });
const b = await j('POST', `/api/projects/${project.id}/todos`, { title: 'Needed snooze thread', spec: 'live walk' });
const sched = await j('POST', '/api/schedules', { todoId: b.id, projectId: project.id, kind: 'daily', at: Date.now() + 3_600_000 });
const snap = async (name) => {
  const todos = await j('GET', '/api/todos');
  const notes = await j('GET', `/api/teams/${teamId}/notifications`);
  const pick = todos.filter((t) => t.id === a.id || t.id === b.id).map(({ id, title, phase, snoozeMode, snoozedUntil }) => ({ id, title, phase, snoozeMode, snoozedUntil }));
  save(name, { todos: pick, unreadThreadIds: notes.unreadThreadIds.filter((id) => id === a.id || id === b.id) });
  return { pick, notes };
};
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 732 } });
const row = (title) => page.getByTestId('sidebar-thread-row').filter({ hasText: title });
const shot = (name) => page.screenshot({ path: `${OUT}/${name}.png` });
await page.goto(`${WEB}/app`);
await row('Timed snooze thread').waitFor();
await page.waitForTimeout(800);
await snap('1-before');
await shot('1-before');
const openSnooze = async (title) => {
  await row(title).hover();
  await row(title).getByTestId('thread-row-menu').click();
  await page.getByTestId('thread-row-snooze').hover();
  await page.getByTestId('thread-snooze-menu').waitFor();
};
await openSnooze('Timed snooze thread');
await shot('2-snooze-menu');
await page.getByTestId('thread-snooze-tomorrow').click();
await row('Timed snooze thread').waitFor({ state: 'detached' });
await openSnooze('Needed snooze thread');
await page.getByTestId('thread-snooze-needed').click();
await page.getByTestId('snooze-confirm').click();
await row('Needed snooze thread').waitFor({ state: 'detached' });
await page.getByTestId('group-snoozed-toggle').click();
await page.waitForTimeout(600);
const mid = await snap('2-snoozed');
await shot('3-snoozed-group');
if (!mid.pick.every((t) => t.snoozeMode != null)) throw new Error('both threads should be snoozed');
await j('DELETE', `/api/schedules/${sched.id}`);
await page.waitForTimeout(1500);
const after = await snap('3-after-schedule-cleared');
await row('Needed snooze thread').waitFor();
await page.mouse.move(900, 600);
await page.locator('body').click({ position: { x: 900, y: 600 } });
await page.getByTestId('unread-dot').first().waitFor();
await shot('4-returned-unread');
const bAfter = after.pick.find((t) => t.id === b.id);
const aAfter = after.pick.find((t) => t.id === a.id);
if (bAfter.snoozeMode !== null || !after.notes.unreadThreadIds.includes(b.id)) throw new Error('needed thread should be back and unread');
if (aAfter.snoozeMode !== 'until') throw new Error('timed thread should stay snoozed');
console.log(JSON.stringify({ ok: true, b: bAfter, a: aAfter }));
await browser.close();
